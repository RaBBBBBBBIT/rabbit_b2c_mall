CREATE TABLE IF NOT EXISTS tb_shop (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  shop_name VARCHAR(120) NOT NULL,
  admin_account VARCHAR(64) NOT NULL,
  admin_password VARCHAR(100) NOT NULL,
  logo_url VARCHAR(500),
  status INTEGER NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_shop_name ON tb_shop(shop_name);
CREATE TABLE IF NOT EXISTS tb_messages (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  shop_id INTEGER NOT NULL,
  sender_id INTEGER,
  title VARCHAR(200) NOT NULL,
  content TEXT NOT NULL,
  msg_type INTEGER NOT NULL DEFAULT 1,
  is_read INTEGER NOT NULL DEFAULT 0,
  read_time DATETIME,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_shop_welcome_message ON tb_messages(shop_id,msg_type,title);
